def load_reviews():
    """수집 CSV를 읽어 리뷰 목록을 돌려준다. 본문은 변조하지 않는다."""
    with CSV_PATH.open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream))
    assert len(rows) == EXPECTED_TOTAL, f'수집 건수 불일치: {len(rows)} != {EXPECTED_TOTAL}'
    ids = [int(r['review_id']) for r in rows]
    assert len(ids) == len(set(ids)), '리뷰 ID 중복'
    return rows


def validate(rows):
    """코딩 누락·잉여·원문 불일치를 전수 확인한다."""
    by_id = {int(r['review_id']): r for r in rows}
    assert set(ANN) == set(by_id), (
        f"코딩 누락: {sorted(set(by_id) - set(ANN))} / 잉여: {sorted(set(ANN) - set(by_id))}")
    for rid, codes in ANN.items():
        body = by_id[rid]['body']
        for code, quote in codes.items():
            assert code in CODEBOOK, f'미정의 코드: {rid}/{code}'
            assert quote in body, f'근거 인용 불일치: {rid}/{code}/{quote!r}'
    dist = Counter(int(r['rating']) for r in rows)
    assert dict(sorted(dist.items(), reverse=True)) == EXPECTED_RATING, f'등급 분포 불일치: {dict(dist)}'


def rate_bucket(rating):
    return '4-5점' if int(rating) >= 4 else '1-3점'


def summarize(rows):
    """전체·색상·한달사용·평점구간별 코드 빈도를 계산한다."""
    groups = {
        'all': rows,
        'color_핑크': [r for r in rows if r['color'] == '핑크'],
        'color_화이트': [r for r in rows if r['color'] == '화이트'],
        'color_미상': [r for r in rows if r['color'] == '미상'],
        'one_month_Y': [r for r in rows if r['is_one_month'] == 'Y'],
        'one_month_N': [r for r in rows if r['is_one_month'] == 'N'],
        'rating_4_5': [r for r in rows if int(r['rating']) >= 4],
        'rating_1_3': [r for r in rows if int(r['rating']) <= 3],
    }
    out = {}
    for name, group in groups.items():
        counts = Counter(code for r in group for code in ANN[int(r['review_id'])])
        out[name] = {
            'denominator': len(group),
            'code_counts': dict(sorted(counts.items())),
            'code_rate_pct': {k: round(v * 100 / len(group), 1) for k, v in sorted(counts.items())},
        }
    return out


